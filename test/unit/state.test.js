'use strict'
const test = require('node:test')
const assert = require('node:assert')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { newTab, reduce, cleanTitle, fmtDur } = require('../../src/main/state')
const fx = (n) => JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'fixtures', n + '.json'), 'utf8'))
const ev = (event, file, extra = {}) => ({ event, payload: { ...fx(file), ...extra } })
const mk = () => newTab({ id: 1, cwd: path.join(os.homedir(), 'proj'), now: 1000 })
const R = (t, e, o = {}) => reduce(t, e, { active: false, now: 5000, ...o })

test('new tab is notStarted, titled by folder', () => { const t = mk(); assert.equal(t.status, 'notStarted'); assert.equal(t.title, 'proj') })
test('SessionStart sets id and transcript, notStarted -> idle', () => {
  const t = R(mk(), ev('SessionStart', 'hook-SessionStart'))
  assert.equal(t.status, 'idle'); assert.equal(t.sessionId, fx('hook-SessionStart').session_id); assert.ok(t.transcriptPath.endsWith('.jsonl'))
})
test('resume SessionStart keeps latest id; /clear style new id replaces it', () => {
  let t = R(mk(), ev('SessionStart', 'hook-SessionStart'))
  t = R(t, ev('SessionStart', 'hook-SessionStart-resume'))
  assert.equal(t.sessionId, fx('hook-SessionStart-resume').session_id)
  t = R(t, ev('SessionStart', 'hook-SessionStart', { session_id: 'new-id', source: 'clear' }))
  assert.equal(t.sessionId, 'new-id')
})
test('UserPromptSubmit -> working, title from prompt only without OSC and rename', () => {
  let t = R(R(mk(), ev('SessionStart', 'hook-SessionStart')), ev('UserPromptSubmit', 'hook-UserPromptSubmit'))
  assert.equal(t.status, 'working'); assert.equal(t.since, 5000)
  assert.equal(t.title, String(fx('hook-UserPromptSubmit').prompt).slice(0, 40))
  const osc = R(R(mk(), { event: '_title', title: '✳ Fix login' }), ev('UserPromptSubmit', 'hook-UserPromptSubmit'))
  assert.equal(osc.title, 'Fix login')
  const ren = R(R(mk(), { event: '_rename', title: 'mine' }), ev('UserPromptSubmit', 'hook-UserPromptSubmit'))
  assert.equal(ren.title, 'mine')
})
test('Stop: done when not active, idle when active; stores lastReply', () => {
  const w = R(mk(), ev('UserPromptSubmit', 'hook-UserPromptSubmit'))
  const d = R(w, ev('Stop', 'hook-Stop'), { active: false })
  assert.equal(d.status, 'done'); assert.equal(d.lastReply, fx('hook-Stop').last_assistant_message)
  assert.equal(R(w, ev('Stop', 'hook-Stop'), { active: true }).status, 'idle')
})
test('selecting a done tab makes it idle; selecting others changes nothing', () => {
  const d = R(R(mk(), ev('UserPromptSubmit', 'hook-UserPromptSubmit')), ev('Stop', 'hook-Stop'))
  assert.equal(R(d, { event: '_select' }).status, 'idle')
  const n = R(d, ev('PreToolUse', 'hook-PreToolUse-AskUserQuestion'))
  assert.equal(R(n, { event: '_select' }).status, 'needs')
})
test('AskUserQuestion Pre -> needs, Post -> working', () => {
  const n = R(mk(), ev('PreToolUse', 'hook-PreToolUse-AskUserQuestion'))
  assert.equal(n.status, 'needs')
  assert.equal(R(n, ev('PostToolUse', 'hook-PostToolUse-AskUserQuestion')).status, 'working')
})
test('Notification: permission and elicitation -> needs, idle ignored', () => {
  const w = R(mk(), ev('UserPromptSubmit', 'hook-UserPromptSubmit'))
  assert.equal(R(w, ev('Notification', 'hook-Notification-permission')).status, 'needs')
  assert.equal(R(w, ev('Notification', 'hook-Notification-elicitation')).status, 'needs')
  assert.equal(R(w, ev('Notification', 'hook-Notification-idle')).status, 'working')
})
test('needs stays through unrelated events, clears on a tool event', () => {
  const n = R(R(mk(), ev('UserPromptSubmit', 'hook-UserPromptSubmit')), ev('Notification', 'hook-Notification-permission'))
  assert.equal(R(n, ev('Notification', 'hook-Notification-idle')).status, 'needs')
  assert.equal(R(n, ev('PreToolUse', 'hook-PreToolUse-Agent')).status, 'working')
})
test('subagents: Pre adds, Post closes by id, SubagentStop closes oldest running', () => {
  let t = R(mk(), ev('UserPromptSubmit', 'hook-UserPromptSubmit'))
  t = R(t, ev('PreToolUse', 'hook-PreToolUse-Agent'))
  assert.equal(t.subagents.length, 1); assert.equal(t.subagents[0].desc, 'Find usages'); assert.ok(t.subagents[0].running)
  assert.equal(R(t, ev('PostToolUse', 'hook-PostToolUse-Agent')).subagents[0].running, false)
  assert.equal(R(t, ev('SubagentStop', 'hook-SubagentStop')).subagents[0].running, false)
  t = R(t, ev('PreToolUse', 'hook-PreToolUse-Agent', { tool_use_id: 'b' }))
  const s = R(t, ev('SubagentStop', 'hook-SubagentStop'))
  assert.deepEqual(s.subagents.map((x) => x.running), [false, true])
})
test('SessionEnd and pty exit -> exited, then SessionStart revives it', () => {
  const s = R(mk(), ev('SessionStart', 'hook-SessionStart'))
  assert.equal(R(s, ev('SessionEnd', 'hook-SessionEnd')).status, 'exited')
  const e = R(s, { event: '_exit' })
  assert.equal(e.status, 'exited')
  assert.equal(R(e, ev('SessionStart', 'hook-SessionStart-resume')).status, 'idle')
  assert.equal(R(mk(), { event: '_exit' }).status, 'notStarted')
})
test('reduce does not mutate its input', () => {
  const t = mk(); Object.freeze(t); Object.freeze(t.subagents)
  assert.doesNotThrow(() => R(t, ev('PreToolUse', 'hook-PreToolUse-Agent')))
})
test('title glyphs are stripped; empty ignored; rename blank resets', () => {
  assert.equal(cleanTitle('⠂ Build thing'), 'Build thing'); assert.equal(cleanTitle('✳ Claude'), 'Claude'); assert.equal(cleanTitle('⠂ '), '')
  assert.equal(R(mk(), { event: '_title', title: '⠂ ' }).hasOsc, false)
  const r = R(R(mk(), { event: '_rename', title: 'x' }), { event: '_rename', title: '  ' })
  assert.equal(r.renamed, false); assert.equal(r.title, 'proj')
})
test('fmtDur', () => { assert.equal(fmtDur(12 * 60000), '12m'); assert.equal(fmtDur(2 * 3600000), '2h'); assert.equal(fmtDur(50 * 3600000), '2d') })
