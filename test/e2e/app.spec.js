test('2 xterm font Hack Nerd Font Mono 18.7px; UI text >= 13px; boxes fit their lines', async () => {
  const o = await h.page.evaluate((i) => window.__ovTest.opts(i), await activeId())
  assert.match(o.fontFamily, /^"Hack Nerd Font Mono", "JetBrains Mono"/); assert.equal(o.fontSize, 18.67)
  await sleep(600)
  const r = await h.page.evaluate(() => {
    const small = []
    document.querySelectorAll('body *').forEach((el) => {
      if (el.closest('.xterm') || el.closest('svg') || ['SCRIPT', 'STYLE', 'I', 'B'].includes(el.tagName) && !el.textContent.trim()) return
      if (!el.offsetParent && getComputedStyle(el).position !== 'fixed') return
      const own = [...el.childNodes].some((n) => n.nodeType === 3 && n.textContent.trim())
      if (!own) return
      const fs = parseFloat(getComputedStyle(el).fontSize)
      if (fs < 13) small.push(el.className + ':' + el.textContent.trim().slice(0, 20) + ':' + fs)
    })
    const clipped = [...document.querySelectorAll('.box .bl')].filter((l) => l.scrollWidth > l.clientWidth + 1).map((l) => l.textContent)
    const px = (s) => parseFloat(getComputedStyle(document.querySelector(s)).fontSize)
    const boxFam = getComputedStyle(document.querySelector('.box')).fontFamily
    const hackOk = document.fonts.check('18.67px "Hack Nerd Font Mono"')
    return { small, clipped, side: document.querySelector('#side').getBoundingClientRect().width, tab: px('.tab'), meta: px('.t-meta'), btn: px('.tb-btn'), status: px('#statusbar'), box: px('.box'), boxFam, hackOk }
  })
  assert.deepEqual(r.small, [], 'no text under 13px')
  assert.deepEqual(r.clipped, [], 'box lines are not cut')
  assert.ok(r.side <= 420, 'right column <= 420 px: ' + r.side)
  assert.ok(r.tab >= 17 && r.meta >= 14 && r.btn >= 15 && r.status >= 14, JSON.stringify(r))
  // the boxes use the terminal's font and size
  assert.equal(r.box, 18.67, 'box font size'); assert.match(r.boxFam, /^"Hack Nerd Font Mono"/); assert.ok(r.hackOk, 'Hack Nerd Font Mono is available')
  assert.equal(o.lineHeight, 1, 'natural line height like Konsole')
})

