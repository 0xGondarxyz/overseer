test('8 Konsole basics: Ctrl+Shift+C/V round trip, PRIMARY + middle-click, right-click menu, scrollback, Ctrl+V is ^V', async () => {
  await go(1)
  const id = await activeId()
  await typeLine('clear'); await typeLine('echo ZZCOPY42')
  await waitText(/^ZZCOPY42$/m)
  const sel = await h.page.evaluate((i) => window.__ovTest.selectText(i, 'ZZCOPY42'), id)
  assert.equal(sel, 'ZZCOPY42')
  await until(async () => (await h.app.evaluate(({ clipboard }) => { try { return clipboard.readText('selection') } catch { return '' } })) === 'ZZCOPY42', 3000).catch(() => {})
  await h.page.keyboard.press('Control+Shift+C')
  await until(async () => (await h.app.evaluate(({ clipboard }) => clipboard.readText())) === 'ZZCOPY42')
  await h.page.evaluate((i) => window.__ovTest.clearSel(i), id)
  const before = count(await screen(), 'ZZCOPY42')
  await h.page.keyboard.press('Control+Shift+V')
  await until(async () => count(await screen(), 'ZZCOPY42') === before + 1)
  // middle-click in the terminal pastes the PRIMARY selection (the selection set above)
  const box = await h.page.locator('.term-host.active .xterm-screen').boundingBox()
  await h.page.mouse.click(box.x + 200, box.y + 100, { button: 'middle' })
  await until(async () => count(await screen(), 'ZZCOPY42') === before + 2)
  // right-click menu
  await h.page.mouse.click(box.x + 200, box.y + 100, { button: 'right' })
  assert.ok(await h.page.locator('#ctx').isVisible())
  assert.deepEqual(await h.page.locator('#ctx button').allTextContents(), ['Copy', 'Paste'])
  await h.page.keyboard.press('Control+u')
  await h.page.mouse.click(box.x + 400, box.y + 300)
  const c1 = count(await screen(), 'ZZCOPY42')
  assert.ok(await h.page.locator('#ctx').isHidden())
  // Ctrl+V reaches the pty and nothing is pasted (no double paste)
  await typeLine('stty -icanon -echo; cat -v')
  await sleep(800)
  await h.page.keyboard.press('Control+v')
  await waitText(/\^V/)
  const t = await screen()
  assert.equal(count(t, 'ZZCOPY42'), c1, 'Ctrl+V did not paste')
  await h.page.keyboard.press('Control+c')
  await typeLine('stty sane')
  // scrollback: wheel and Shift+PageUp
  await typeLine('seq 1 300')
  await waitText(/^300$/m)
  const vy = () => h.page.evaluate((i) => window.__ovTest.scroll(i), id)
  const s0 = await vy(); assert.equal(s0.y, s0.base)
  await h.page.mouse.move(box.x + 300, box.y + 200)
  await h.page.mouse.wheel(0, -600)
  await until(async () => (await vy()).y < s0.y)
  await h.page.keyboard.press('End')
  await h.page.evaluate((i) => window.__ovTest.toBottom(i), id)
  const s1 = await vy(); assert.equal(s1.y, s1.base)
  await h.page.keyboard.press('Shift+PageUp')
  await until(async () => (await vy()).y < s1.y)
  await h.page.keyboard.press('Shift+PageDown')
  await until(async () => (await vy()).y === s1.y)
})

